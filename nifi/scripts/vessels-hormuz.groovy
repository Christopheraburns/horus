/**
 * NiFi ExecuteScript: hormuz.now live snapshot -> canonical horus-events Kafka messages.
 *
 * Input:  FlowFile body = hormuz.now JSON from InvokeHTTP
 *         GET https://hormuz.now/api/snapshot   (the full format, not ?format=compact:
 *         only the full format carries MMSI)
 *         { "fetchedAt": <epoch ms>, "bbox": {...}, "count": n,
 *           "vessels": [ { id, mmsi, name, lat, lon, speed, course, heading,
 *                          destination, flag, length, width, dwt, category,
 *                          shiptypeLabel, elapsedMin, posAt, ... } ] }
 * Output: one FlowFile per vessel that moved (or is due a heartbeat), in the
 *         same envelope as the aisstream.io flow (schema_version 1).
 *
 * Source of truth for the script body in nifi/HORUS_Vessels_hormuz.now.json; that
 * flow file is generated by tools/build_hormuz_flow.py.
 *
 * Identity (the multi-source test):
 *   - entity.id = MMSI, the same key the aisstream.io flow uses, so the lake and
 *     the gateway see both sources' reports of a ship as one asset.
 *   - entity.source.originalId = hormuz.now's own vessel id (the lake's event_id),
 *     so each source's observation stays a separate row.
 *   - No valid 9-digit MMSI: entity.id = "hormuz.now:<id>" (not linkable).
 *
 * Re-sends: hormuz.now republishes every vessel on every poll, and posAt is
 * derived from elapsedMin (whole minutes) at fetch time, so it shifts on each
 * poll and Flink's (event_id, event_time) dedupe cannot catch repeats. This
 * script remembers, in the processor's local state, the last position and time
 * it emitted per vessel and only emits when the position changes, or every
 * HEARTBEAT_S seconds so stationary ships stay on the live map (a heartbeat
 * reuses the previous time, so the lake drops it as a duplicate).
 *
 * Licence: hormuz.now data is CC BY 4.0; credit hormuz.now with a link
 * (carried as properties.attribution).
 *
 * Explicit f['key'] bracket access throughout (Groovy bean-accessor trap).
 */
import groovy.json.JsonSlurper
import groovy.json.JsonOutput
import java.time.Instant
import java.time.ZoneOffset
import java.time.format.DateTimeFormatter
import org.apache.nifi.components.state.Scope

def flowFile = session.get()
if (!flowFile) return

def MAX_AGE_MIN = 60        // older reports are dropped (gateway TTL is at most 60 min)
def HEARTBEAT_S = 600       // re-send an unchanged vessel this often (moving-vessel TTL is 20 min)
def SKIP_CATEGORIES = ['navaid'] as Set   // aids to navigation are not vessels
def MMSI_RE = ~/^\d{9}$/

def ISO = DateTimeFormatter.ofPattern("yyyy-MM-dd'T'HH:mm:ss'Z'")
def iso = { long epochSeconds -> Instant.ofEpochSecond(epochSeconds).atOffset(ZoneOffset.UTC).format(ISO) }

def payload
try {
    payload = new JsonSlurper().parseText(session.read(flowFile).text)
} catch (Exception e) {
    log.warn("Unparseable hormuz.now snapshot: ${e.message}")
    session.transfer(flowFile, REL_FAILURE)
    return
}
def vessels = payload instanceof Map ? payload['vessels'] : null
if (!(vessels instanceof List)) {
    log.warn("hormuz.now snapshot has no vessels array")
    session.transfer(flowFile, REL_FAILURE)
    return
}

def nowS = Instant.now().epochSecond
def fetchedS = (payload['fetchedAt'] instanceof Number) ? ((payload['fetchedAt'] as long) / 1000L) as long : nowS
def capturedAt = iso(nowS)
def ingestRunId = flowFile.getAttribute('ingest.run.id') ?: ('nifi-' + UUID.randomUUID().toString().take(12))
def provider  = 'hormuz.now'
def feed      = 'vessels'
def sourceUrl = 'https://hormuz.now/api/snapshot'

// Last emitted per vessel: id -> "lat,lon|eventTimeS|emittedAtS"
def stateManager = context.stateManager
def previous = stateManager.getState(Scope.LOCAL).toMap()
def nextState = [:]

def emitted = 0, moved = 0, heartbeats = 0, unchanged = 0, skipped = 0

vessels.each { v ->
    if (!(v instanceof Map)) { skipped++; return }
    def id  = v['id'] != null ? v['id'].toString() : ''
    def lat = v['lat'], lon = v['lon']
    def category = ((v['category'] ?: 'unknown') as String).toLowerCase()
    def ageMin = (v['elapsedMin'] instanceof Number) ? (v['elapsedMin'] as int) : 0
    if (!id || !(lat instanceof Number) || !(lon instanceof Number)) { skipped++; return }
    if (SKIP_CATEGORIES.contains(category) || ageMin > MAX_AGE_MIN) { skipped++; return }

    def pos = "${lat},${lon}"
    def posAtS = (v['posAt'] instanceof Number) ? ((v['posAt'] as long) / 1000L) as long : fetchedS - ageMin * 60L
    def prev = previous[id]?.split('\\|')
    long eventS
    if (prev && prev.length == 3 && prev[0] == pos) {
        if (nowS - (prev[2] as long) < HEARTBEAT_S) {       // nothing new
            nextState[id] = previous[id]
            unchanged++
            return
        }
        eventS = prev[1] as long                              // heartbeat: same time
        heartbeats++
    } else {
        eventS = posAtS
        if (prev && prev.length == 3) {
            // A new position must not reuse an earlier time, or Flink drops it.
            eventS = Math.max(eventS, (prev[1] as long) + 1L)
        }
        moved++
    }
    nextState[id] = "${pos}|${eventS}|${nowS}".toString()

    def mmsiStr = v['mmsi'] != null ? v['mmsi'].toString().trim() : ''
    def hasMmsi = MMSI_RE.matcher(mmsiStr).matches()
    def entityId = hasMmsi ? mmsiStr : "hormuz.now:${id}".toString()
    def name = ((v['name'] ?: '') as String).trim() ?: entityId

    def course = v['course']
    def heading = v['heading']
    if (!(heading instanceof Number) || (heading as int) == 511) heading = course

    def props = [
        hormuz_id     : id,
        type          : category == 'tanker' ? 'tanker' : category,   // UI colours tanker / military
        category      : category,
        shiptype_label: (v['shiptypeLabel'] ?: ''),
        sog           : v['speed'],
        cog           : course,
        heading       : heading,
        destination   : ((v['destination'] ?: '') as String).trim(),
        flag          : (v['flag'] ?: ''),
        length        : v['length'],
        width         : v['width'],
        dwt           : v['dwt'],
        age_min       : ageMin,
        attribution   : 'hormuz.now (CC BY 4.0) https://hormuz.now',
    ]
    if (hasMmsi) props['mmsi'] = mmsiStr as Long

    def entity = [
        id            : entityId,
        name          : name,
        domain        : 'SEA',
        entityType    : 'VESSEL',
        position      : [lat: lat as Double, lng: lon as Double, alt: 0.0d],
        threat        : 'NONE',
        classification: 'UNCLASSIFIED',
        confidence    : 0.7,
        timestamp     : iso(eventS),
        source        : [
            provider  : provider,
            feed      : feed,
            originalId: id,
            confidence: 0.7,
            sourceUrl : sourceUrl,
        ],
        properties    : props,
    ]

    def traceId = UUID.randomUUID().toString()
    def envelope = [
        schema_version: 1,
        trace_id      : traceId,
        ingest_run_id : ingestRunId,
        source        : feed,
        captured_at   : capturedAt,
        entity        : entity,
    ]

    def out = session.create(flowFile)
    out = session.write(out, { outStream ->
        outStream.write(JsonOutput.toJson(envelope).getBytes('UTF-8'))
    } as OutputStreamCallback)
    out = session.putAttribute(out, 'mime.type', 'application/json')
    out = session.putAttribute(out, 'kafka.key', entityId)
    out = session.putAttribute(out, 'trace.id', traceId)
    session.transfer(out, REL_SUCCESS)
    emitted++
}

stateManager.setState(nextState, Scope.LOCAL)
log.info("hormuz.now: ${vessels.size()} vessels, emitted ${emitted} (${moved} moved, ${heartbeats} heartbeats), ${unchanged} unchanged, ${skipped} skipped")
session.remove(flowFile)
